void sub__capslock(int32_t options) {
    OPTIONAL_GLUT();

    auto currentState = GLUTEmu_KeyboardIsKeyModifierSet(GLUTEmu_KeyboardKeyModifier::CapsLock);
    switch (options) {
    case 1: // ON
        if (currentState)
            return;
        break;
    case 2: // OFF
        if (!currentState)
            return;
        break;
    }

    // _TOGGLE:
    GLUTEmu_KeyboardToggleLockKeyState(GLUTEmu_KeyboardKeyModifier::CapsLock);
}

